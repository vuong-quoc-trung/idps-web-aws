        constraint ck_training_program_academic_numbers check ((number_of_semesters IS NULL OR number_of_semesters > 0) AND (total_credits IS NULL OR total_credits >= 0) AND (required_credits IS NULL OR required_credits >= 0) AND (elective_credits IS NULL OR elective_credits >= 0) AND (total_credits IS NULL OR required_credits IS NULL OR required_credits <= total_credits) AND (total_credits IS NULL OR elective_credits IS NULL OR elective_credits <= total_credits) AND (total_credits IS NULL OR required_credits IS NULL OR elective_credits IS NULL      OR CAST(required_credits AS BIGINT) + CAST(elective_credits AS BIGINT) = total_credits) )
